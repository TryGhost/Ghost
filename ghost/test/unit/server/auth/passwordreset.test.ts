import assert from 'node:assert/strict';
import sinon from 'sinon';
import * as security from '@tryghost/security';
// @ts-expect-error This module lacks type definitions.
import passwordreset from '../../../../core/server/auth/passwordreset';
// @ts-expect-error This module lacks type definitions.
import models from '../../../../core/server/models';
// @ts-expect-error This module lacks type definitions.
import ghostBookshelf from '../../../../core/server/models/base';

type TestUser = {
  get(key: 'password'): string;
  set(key: 'password', value: string): void;
  save(): Promise<TestUser>;
};

describe('Password reset token compatibility', function () {
  const email = 'Mixed+Case@example.com';
  const dbHash = 'test-site-secret';
  const passwordHash = '$2a$10$t5dY1uRRdjvqfNlXhae3uuc0nuhi.Rd7/K/9JaHHwSkLm6UUa3NsW';
  // Generated by @tryghost/security 3.3.18 using the same stored hash and site secret.
  const legacyToken =
    'NDEwMjQ0NDgwMDAwMHxNaXhlZCtDYXNlQGV4YW1wbGUuY29tfGxQbk0vVmpEQXJpdk5XSWZyU1JUTnRtK2ZEdG5TMTlkLzhvejQ4RWlsOFU9';
  let user: TestUser;
  let settingsAPI: {
    read: sinon.SinonStub<[object], Promise<{ settings: { value: string }[] }>>;
  };
  let replacementHash: string;
  let changePassword: sinon.SinonStub;

  beforeEach(async function () {
    replacementHash = await security.password.hash('replacement-test-only');
    user = new models.User({
      id: '000000000000000000000001',
      email,
      password: passwordHash,
      status: 'active',
    });
    settingsAPI = {
      read: sinon
        .stub<[object], Promise<{ settings: { value: string }[] }>>()
        .resolves({ settings: [{ value: dbHash }] }),
    };
    sinon.stub(models.User, 'getByEmail').resolves(user);
    sinon.stub(models.User.prototype, 'fetch').resolves(user);
    sinon
      .stub(ghostBookshelf, 'transaction')
      .callsFake(async (callback: (transaction: object) => Promise<unknown>) => callback({}));
    changePassword = sinon.stub(models.User, 'changePassword').callsFake(async () => {
      user.set('password', replacementHash);
      return user;
    });
    sinon.stub(user, 'save').resolves(user);
  });

  afterEach(function () {
    sinon.restore();
  });

  it('generates a reset token with the published security API', async function () {
    const result = await passwordreset.generateToken(email, settingsAPI);
    assert.equal(result.email, email);
    assert.deepEqual(
      security.tokens.resetToken.compare({ token: result.resetToken, dbHash, passwordHash }),
      { correct: true },
    );
  });

  it('accepts a pre-rename token through Ghost and invalidates it after the password changes', async function () {
    const options = {
      data: {
        password_reset: [
          {
            token: legacyToken,
            oldPassword: 'old-test-only',
            newPassword: 'replacement-test-only',
          },
        ],
      },
    };
    const parts = security.tokens.resetToken.extract({ token: legacyToken });
    const result = await passwordreset.doReset(options, parts, settingsAPI);
    assert.equal(result.user, user);
    sinon.assert.calledOnce(changePassword);
    assert.deepEqual(
      security.tokens.resetToken.compare({
        token: legacyToken,
        dbHash,
        passwordHash: user.get('password'),
      }),
      { correct: false, reason: 'invalid' },
    );
  });

  it('rejects a token through Ghost if the stored password hash has changed', async function () {
    user.set('password', replacementHash);
    const options = {
      data: { password_reset: [{ token: legacyToken, newPassword: 'replacement-test-only' }] },
    };
    await assert.rejects(
      passwordreset.doReset(
        options,
        security.tokens.resetToken.extract({ token: legacyToken }),
        settingsAPI,
      ),
      /Cannot reset password/,
    );
    sinon.assert.notCalled(changePassword);
  });
});
