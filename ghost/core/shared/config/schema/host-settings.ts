import { z } from 'zod';

/**
 * Settings Ghost(Pro) injects through environment variables. Self-hosted sites
 * do not set them, so every key is optional.
 *
 * Loose: most hostSettings keys have no schema yet, and none may be stricter
 * than what Pro sets.
 */
export const hostSettings = z
  .looseObject({
    export: z
      .object({
        webhookUrl: z
          .string()
          .optional()
          .meta({
            description:
              'Where async export requests are sent. Unset, the site cannot request one.',
            examples: ['https://exports.example.com/requests'],
          }),
        webhookSecret: z.string().optional().meta({
          description: 'Signs async export requests. Required when webhookUrl is set.',
        }),
      })
      .optional()
      .meta({ description: 'Async exports, generated by the host instead of Ghost.' }),
  })
  .optional()
  .meta({ description: 'Set by the hosting platform, not by a self-hoster.', internal: true });
